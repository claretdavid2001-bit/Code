def mercado(ticker: str) -> str:
    if ticker.endswith(".MC"):
        return "España"
    if "." in ticker and not ticker.endswith("-B"):
        return "Europa"
    return "EE. UU."


def es_usd(ticker: str) -> bool:
    return mercado(ticker) == "EE. UU."
